def water_footprint(mass_ton: float, stages_data: dict) -> dict:
    """精炼过程水足迹 + 废水指标预测"""
    degum = stages_data.get("脱胶", {}).get("计算结果", {})
    neut = stages_data.get("碱炼脱酸", {}).get("计算结果", {})

    # 用水量
    water_degum = float(str(degum.get("加水量_kg", mass_ton * 30)).replace("kg", "").strip() or mass_ton * 30)
    water_wash = mass_ton * 1000 * 0.10  # 碱炼洗涤水 10%
    water_cooling = mass_ton * 200  # 冷却循环水(大部分回用)

    total_fresh = water_degum + water_wash
    total_with_cooling = total_fresh + water_cooling * 0.1  # 冷却水补充10%

    # 废水COD预测
    cod_gum = float(str(degum.get("脱除磷脂质量_kg", mass_ton * 1000 * 0.025)).replace("kg", "").strip() or mass_ton * 1000 * 0.025)
    cod_soap = float(str(neut.get("总皂脚量_kg", mass_ton * 1000 * 0.04)).replace("kg", "").strip() or mass_ton * 1000 * 0.04) * 0.05
    total_cod = (cod_gum + cod_soap) * 1000  # 转为g
    wastewater_vol = (water_degum + water_wash) / 1000  # 转为m³
    cod_mg_per_l = total_cod / (wastewater_vol * 1000) if wastewater_vol > 0 else 0

    # 废水磷含量
    p_in_water = float(str(degum.get("初始磷含量_ppm", 800)).replace("ppm", "").strip() or 800) * mass_ton * 1000 / 1e6 * 0.85
    wastewater_p_mg_per_l = p_in_water * 1000 / (wastewater_vol * 1000) if wastewater_vol > 0 else 0

    compliance = cod_mg_per_l <= 500 and wastewater_p_mg_per_l <= 8

    return {
        "新鲜水用量_吨每批": round(total_fresh / 1000, 1),
        "含冷却水总用量_吨每批": round(total_with_cooling / 1000, 1),
        "废水产生量_m3每批": round(wastewater_vol, 1),
        "废水COD_预估_mg每L": round(cod_mg_per_l, 0),
        "废水中磷_预估_mg每L": round(wastewater_p_mg_per_l, 1),
        "排放合规(GB 8978)": "✅ 预计达标" if compliance else "⚠ 可能需要处理",
        "节水建议": [
            "冷却水循环使用(可回用90%以上)",
            "碱炼洗涤水逆流使用可节水30-40%",
            "脱胶废水可经酸化处理后部分回用",
        ],
    }


