def benchmark_ranking(oil_name: str, output: dict, deod_stage: dict = None) -> dict:
    """行业对标排名: 告诉你处于行业什么位置"""
    bm = BENCHMARK_DATA.get(oil_name, BENCHMARK_DATA["default"])
    results = {}

    yield_pct = output.get("yield_pct", 92)
    steam = 120
    if deod_stage:
        s = str(deod_stage.get("吨油耗汽_kg蒸汽每吨油", 120))
        steam = float(s.replace("kg", "").split("kg")[0].strip() or 120)

    for metric, data, value, unit in [
        ("精炼得率", bm["yield_pct"], yield_pct, "%"),
        ("蒸汽单耗", bm["steam_kg_per_ton"], steam, "kg/t"),
    ]:
        percentile = "后10%"
        color = "#c0392b"
        if value <= data["p25"] if metric == "蒸汽单耗" else value >= data["p25"]:
            if metric == "蒸汽单耗":
                if value <= data["best"]:
                    percentile = "前5% (顶尖)"
                    color = "#27ae60"
                elif value <= data["p25"]:
                    percentile = "前25%"
                    color = "#27ae60"
                elif value <= data["p50"]:
                    percentile = "前50% (中上)"
                    color = "#2980b9"
                elif value <= data["p75"]:
                    percentile = "后50% (中下)"
                    color = "#e67e22"
                else:
                    percentile = "后25%"
                    color = "#c0392b"
            else:  # yield - higher is better
                if value >= data["best"]:
                    percentile = "前5% (顶尖)"
                    color = "#27ae60"
                elif value >= data["p75"]:
                    percentile = "前25%"
                    color = "#27ae60"
                elif value >= data["p50"]:
                    percentile = "前50% (中上)"
                    color = "#2980b9"
                elif value >= data["p25"]:
                    percentile = "后50% (中下)"
                    color = "#e67e22"
                else:
                    percentile = "后25%"
                    color = "#c0392b"

        gap = data["best"] - value
        if metric == "蒸汽单耗":
            gap = value - data["best"]

        results[metric] = {
            "当前值": f"{value} {unit}",
            "行业百分位": percentile,
            "行业最优": f"{data['best']} {unit}",
            "距最优差距": f"{gap:.1f} {unit}",
            "改进潜力": f"若达到P50水平, 年增效约 ¥{abs(gap)*70*300/10000:.0f}万" if abs(gap) > 5 else "已达行业先进水平",
        }

    return results


